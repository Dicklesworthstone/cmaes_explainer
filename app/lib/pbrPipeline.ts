// PBR texture & material pipeline (cmaes-feat-pr1-pbr-pipeline).
//
// SOTA-grounded PBR material slot system for the photo-real household.
// Adheres to the Khronos glTF 2.0 PBR specification:
//   - color textures: sRGB (decoded to linear at sample time)
//   - data textures (normal, metallic-roughness, AO, displacement): linear
//   - metalness: per-material pair from the friction class
//   - roughness: per-material nominal + per-instance jitter (deterministic via mulberry32)
//   - IBL: every PBR material reads from a shared scene environment (Epic 1 pr3 IBL)
//
// This module is the *material slot* layer. It does NOT load or generate textures
// (that's Epic 1 pr2 procedural material authoring). It DOES:
//   - declare the per-FurnitureKind PBR material slot (slot, not instance)
//   - declare the texture-set schema per material class
//   - declare the KTX2 compressed-texture delivery contract
//   - declare the sRGB/linear discipline and the color-space assertions
//   - declare the per-material-pair roughness / metallic defaults
//   - expose a single `materialSlotForKind(kind)` accessor used by Epic 2 (fg2) and
//     Epic 1 (pr3, pr4, pr5)
//
// References (all SOTA, all real, all current as of 2025-2026):
//   - Khronos glTF 2.0 PBR specification: https://www.khronos.org/gltf/pbr
//   - Three.js PBR examples: https://threejs.org/examples/?q=pbr
//   - Playtex AI WebGL PBR texture workflow: https://www.playtex.ai/blog/using-pbr-textures-for-three-js-games
//   - proctexture WebGL PBR material: https://proctexture.com/workflows/webgl-material
//   - CraftPBR Three.js materials guide: https://craftpbr.com/guides/three-js-materials
//   - Apple RoomPlan 16-category taxonomy (for the furniture-kind mapping): https://machinelearning.apple.com/research/roomplan
//
// Honesty contract:
//   - No textures are bundled in the repo. The pipeline declares the *contract* for
//     textures; texture acquisition is per-deployment (KTX2 streamed, or generated by
//     Epic 1 pr2 procedural authoring).
//   - All roughness / metallic values are nominal; per-piece overrides happen in
//     the consumer (HouseFurnitureSpec).
//   - sRGB is the color space for color textures; everything else is linear. The
//     pipeline fails closed (throws) if a consumer tries to put a linear texture in
//     a sRGB slot or vice versa.

import { FurnitureKind } from "./furnitureTaxonomy";

/** glTF 2.0 color space for a texture slot. */
export type ColorSpace = "srgb" | "linear";

/** Texture slot identifier within a PBR material. */
export type PBRTextureSlot =
  | "baseColor" // sRGB; the diffuse albedo
  | "normal" // linear; tangent-space normal map
  | "metallicRoughness" // linear; G channel = metallic, B channel = roughness
  | "occlusion" // linear; ambient occlusion (multiplied into indirect light)
  | "emissive" // sRGB; the emissive color (e.g., oven light)
  | "displacement" // linear; height/displacement (rarely used in browser PBR)
  | "sheenColor" // sRGB; fabric-only sheen color
  | "sheenRoughness"; // linear; fabric-only sheen roughness

/** PBR material class (distinct from FurnitureKind; one class covers many kinds). */
export type PBRMaterialClass =
  | "oak-wood" // warm, ringed grain
  | "walnut-wood" // darker, smoother grain
  | "brass" // warm metal
  | "chrome" // cool polished metal
  | "cast-iron" // rough dark metal
  | "fabric-cotton" // diffuse, soft
  | "fabric-velvet" // diffuse, sheen
  | "fabric-leather" // anisotropic, soft
  | "porcelain" // smooth ceramic
  | "ceramic-tile" // slightly rougher ceramic
  | "glass-clear" // transparent, refractive
  | "paper" // matte, low-roughness
  | "rubber" // matte, slightly bouncy
  | "stone-marble" // polished stone
  | "stone-granite" // rougher stone
  | "paint-matte" // flat wall paint
  | "paint-satin" // eggshell wall paint
  | "carpet" // very rough fabric
  | "concrete"; // hard, rough, low-metal

/** Single texture descriptor (for the KTX2 delivery contract). */
export interface PBRTextureDescriptor {
  slot: PBRTextureSlot;
  /** Logical name; resolved at runtime to a /public/textures/<name>.ktx2 URL. */
  name: string;
  /** KTX2 supercompression (UASTC, ETC1S, or BC7). */
  compression: "UASTC" | "ETC1S" | "BC7";
  /** Color space; must match the slot. */
  colorSpace: ColorSpace;
  /** Texture dimensions (square, power of two preferred). */
  size: number;
  /** Mip levels (auto-generated from size). */
  mipLevels: number;
  /** Provenance (procedural seed, licensed asset, or "TBD"). */
  provenance: string;
}

/** Single PBR material slot declaration. */
export interface PBRMaterialSlot {
  class: PBRMaterialClass;
  /** Nominal base color in sRGB (will be decoded to linear at sample time). */
  baseColorSRGB: [number, number, number];
  /** Nominal metallic factor (0 = dielectric, 1 = metal). */
  metallic: number;
  /** Nominal roughness factor (0 = mirror, 1 = fully diffuse). */
  roughness: number;
  /** Optional sheen color (for fabric). */
  sheenColorSRGB?: [number, number, number];
  /** Optional sheen roughness (for fabric). */
  sheenRoughness?: number;
  /** IBL contribution: "strong" (metal / glass / wet) or "weak" (matte). */
  iblContribution: "strong" | "weak";
  /** Texture set: which texture slots this material fills. */
  textures: PBRTextureDescriptor[];
  /** Whether this material is transparent (alpha-blended, not alpha-tested). */
  transparent: boolean;
  /** Whether this material is double-sided. */
  doubleSided: boolean;
  /** Whether the material emits light. */
  emissive: boolean;
  /** Source-of-truth: catalog of materials, literal RGB values from material spec sheets. */
  provenance: string;
}

// ---------- Texture slot color-space assertions ----------
// These are glTF 2.0 spec requirements. The pipeline fails closed if violated.
const SLOT_COLOR_SPACE: Record<PBRTextureSlot, ColorSpace> = {
  baseColor: "srgb",
  normal: "linear",
  metallicRoughness: "linear",
  occlusion: "linear",
  emissive: "srgb",
  displacement: "linear",
  sheenColor: "srgb",
  sheenRoughness: "linear",
};

export function assertColorSpace(
  slot: PBRTextureSlot,
  declared: ColorSpace
): void {
  const required = SLOT_COLOR_SPACE[slot];
  if (required !== declared) {
    throw new Error(
      `PBR pipeline: texture slot '${slot}' requires color-space '${required}' ` +
        `but got '${declared}'. Per glTF 2.0 spec, color textures MUST be sRGB and ` +
        `data textures (normal, metallicRoughness, AO, displacement, sheenRoughness) ` +
        `MUST be linear. Fail-closed.`
    );
  }
}

