/** Resolve the PBR material slot list for a given furniture kind. */
export function materialSlotsForKind(kind: FurnitureKind): PBRMaterialSlot[] {
  const classes = FURNITURE_KIND_TO_PBR_CLASSES[kind];
  return classes.map((c) => PBR_MATERIAL_SLOTS[c]);
}

/** Total texture-set budget across the PBR material table (sum of all texture
 *  descriptors, in MB assuming UASTC @ 8 bpp). Used by the Vercel bundle check. */
export function totalTextureBudgetMB(): number {
  let total = 0;
  for (const slot of Object.values(PBR_MATERIAL_SLOTS)) {
    for (const tex of slot.textures) {
      // UASTC: 8 bpp; ETC1S: 4 bpp; BC7: 8 bpp
      const bpp = tex.compression === "ETC1S" ? 4 : 8;
      // Mip-map chain: factor = 4/3 of base
      const basePixels = tex.size * tex.size;
      const totalPixels = basePixels * (4 / 3);
      total += (totalPixels * bpp) / 8 / 1024 / 1024; // bytes -> MB
    }
  }
  return total;
}

